import type { NextPage } from "next";
import Head from "next/head";
import Link from "next/link";
import { useCallback, useEffect, useState } from "react";
import { signIn, useSession } from "next-auth/react";
import { useForm, Controller } from "react-hook-form";
import { zodResolver } from "@hookform/resolvers/zod";
import Layout from "../../components/ui/Layout";
import { useRouter } from "next/router";
import { Role } from "@prisma/client";

import { IAdminLogin, adminLoginSchema } from "../../common/validation/auth";

const adminLogin: NextPage = () => {
  const { handleSubmit, control, reset } = useForm<IAdminLogin>({
    defaultValues: {
      email: "",
      password: "",
    },
    resolver: zodResolver(adminLoginSchema),
  });

  // const { status } = useSession();
  const Router = useRouter();
  const { data: session, status } = useSession();
  const router = useRouter();

  const [loginAttempted, setLoginAttempted] = useState(false);

  useEffect(() => {
    if (status === "authenticated" && loginAttempted) {
      if (session.user.role === Role.ADMIN) {
        Router.replace("/admin/dashboard");
      } else {
        router.push("/401");
      }
    }
  }, [status, session, router, loginAttempted]);

  const onSubmit = useCallback(
    async (data: IAdminLogin) => {
      setLoginAttempted(true); // Add this line

      console.log(onSubmit);
      try {
        await signIn("AdminCredentials", {
          ...data,
          callbackUrl: "/admin/dashboard",
          redirect: false, // Add this line
        });

        reset();
      } catch (err) {
        console.error(err);
      }
    },
    [reset]
  );

  return (
    <>
      <Head>
        <title>Next App - Login Admin</title>
        <meta name='description' content='Generated by create next app' />
        <link rel='icon' href='/favicon.ico' />
      </Head>
      <Layout>
        <main>
          <form
            className='flex items-center justify-center h-screen w-full'
            onSubmit={handleSubmit(onSubmit)}
          >
            <div className='card w-96 bg-base-100 shadow-xl'>
              <div className='card-body'>
                <h2 className='card-title'>Welcome back person Admin!</h2>
                <Controller
                  name='email'
                  control={control}
                  render={({ field }) => (
                    <input
                      type='email'
                      placeholder='Type your email...'
                      className='input input-bordered w-full max-w-xs'
                      {...field}
                    />
                  )}
                />

                <Controller
                  name='password'
                  control={control}
                  render={({ field }) => (
                    <input
                      type='password'
                      placeholder='Type your password...'
                      className='input input-bordered w-full max-w-xs my-2'
                      {...field}
                    />
                  )}
                />
                <div className='card-actions items-center justify-between'>
                  <Link href='/admin/sign-up' className='link'>
                    Go to sign up
                  </Link>

                  <button className='btn btn-secondary' type='submit'>
                    Login
                  </button>
                </div>
              </div>
            </div>
          </form>
        </main>
      </Layout>
    </>
  );
};

export default adminLogin;

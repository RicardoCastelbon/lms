import type { NextPage } from "next";
import Head from "next/head";
import Link from "next/link";
import { useCallback } from "react";
import { useRouter } from "next/router";
import { useForm, Controller } from "react-hook-form";
import { zodResolver } from "@hookform/resolvers/zod";

import {
  adminSignUpSchema,
  IAdminSignUp,
  IAdminLogin,
  adminLoginSchema,
} from "../../common/validation/auth";
import { trpc } from "../../common/trpc";
import { log } from "console";

const adminSignUp: NextPage = () => {
  const router = useRouter();
  const { handleSubmit, control, reset } = useForm<IAdminLogin>({
    defaultValues: {
      email: "",
      password: "",
    },
    resolver: zodResolver(adminLoginSchema),
  });

  const { mutateAsync } = trpc.admin.signup.useMutation();

  const onSubmit = useCallback(
    async (data: IAdminLogin) => {
      console.log("hej", data); // log the data object

      try {
        const result = await mutateAsync(data);
        console.log("result", result); // log the result object

        if (result && result.status === 201) {
          reset();
          router.push("/admin/login");
        }
      } catch (err) {
        console.error(err);
      }
    },
    [mutateAsync, router, reset]
  );

  return (
    <div>
      <Head>
        <title>Next App - Register Admin</title>
        <meta name='description' content='Generated by create next app' />
        <link rel='icon' href='/favicon.ico' />
      </Head>

      <main className="flex items-center justify-center min-h-screen">
  <form
    className="flex flex-col items-center justify-center w-full px-4 sm:px-8"
    onSubmit={handleSubmit(onSubmit)}
  >
    <div className="flex flex-col items-center justify-center bg-white p-8 shadow-xl rounded-lg w-80">
      <h2 className="text-2xl mb-6">Create an account!</h2>

      <Controller
        name="email"
        control={control}
        render={({ field }) => (
          <input
            type="email"
            placeholder="Type your email..."
            className="input input-bordered w-full mb-4 bg-gray-200 rounded"
            {...field}
          />
        )}
      />

      <Controller
        name="password"
        control={control}
        render={({ field }) => (
          <input
            type="password"
            placeholder="Type your password..."
            className="input input-bordered w-full mb-4 bg-gray-200 rounded"
            {...field}
          />
        )}
      />

      <div className="flex items-center justify-between w-full">
        <Link href="/admin/login">
          <p className="text-purple-600 hover:text-purple-800">Go to login</p>
        </Link>

        <button
          className="btn btn-secondary bg-purple-600 text-white py-2 px-4 rounded"
          type="submit"
        >
          Sign Up
        </button>
      </div>
    </div>
  </form>
</main>

    </div>
  );
};

export default adminSignUp;

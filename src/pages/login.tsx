import type { NextPage } from "next";
import Head from "next/head";
import Link from "next/link";
import { useCallback, useEffect, useState } from "react";
import { signIn, useSession } from "next-auth/react";
import { useForm, Controller } from "react-hook-form";
import { zodResolver } from "@hookform/resolvers/zod";

import { loginSchema, ILogin } from "../common/validation/auth";
import Layout from "../components/ui/Layout";
import { Button } from "../components/ui/button";
import { useRouter } from "next/router";
import { Role } from "@prisma/client";

const Login: NextPage = () => {
  const router = useRouter();
  const { data, status } = useSession();
  const [loginAttempt, setLoginAttempt] = useState<boolean>(false);

  useEffect(() => {
    if (status === "authenticated" && loginAttempt) {
      if (data.user.role === Role.STUDENT || Role.TEACHER) {
        router.replace(`/dashboard`);
      }
    }
  }, [status, data, router, loginAttempt]);
  const {
    handleSubmit,
    control,
    reset,
    formState: { errors },
    setValue,
  } = useForm<ILogin>({
    defaultValues: {
      email: "",
      password: "",
    },
  });

  const onSubmit = useCallback(
    async (credentials: ILogin) => {
      try {
        const res = await signIn("Mycredentials", {
          ...credentials,
          redirect: false,
        });
        if (res?.status === 200) {
          setLoginAttempt(true);
        }
        console.log("res", res);

        reset();
      } catch (err) {
        console.error(err);
      }
    },
    [reset]
  );

  return (
    <>
      <Head>
        <title>Next App - Login</title>
        <meta name="description" content="Generated by create next app" />
        <link rel="icon" href="/favicon.ico" />
      </Head>
      <Layout>
        <div className="flex flex-1 items-center justify-center relative w-full h-full p-4">
          <form
            className="flex flex-col items-center gap-4 h-full w-full md:w-4/6 bg-white px-4 py-10 rounded-lg shadow-xl"
            onSubmit={handleSubmit(onSubmit)}
          >
            <h2 className="text-xl mb-8">Välkommen tillbaka!</h2>
            <Controller
              name="email"
              control={control}
              rules={{ required: "Ange din email" }}
              render={({
                field: { value, onChange, onBlur, name, ...field },
              }) => (
                <div className="w-full max-w-md flex flex-col mb-4">
                  <label htmlFor="education">E-post</label>
                  <input
                    {...field}
                    value={value}
                    name={name}
                    onChange={onChange}
                    onBlur={onBlur}
                    type="email"
                    placeholder="Ange din e-post..."
                    className="input bg-muted h-[40px] input-bordered w-full mt-2 rounded-md pl-2"
                  />
                  <p className="text-xs text-red-500 mt-1">
                    {errors?.email?.message}
                  </p>
                </div>
              )}
            />

            <Controller
              name="password"
              control={control}
              rules={{ required: "Ange ditt lösenord" }}
              render={({
                field: { value, onChange, onBlur, name, ...field },
              }) => (
                <div className="w-full max-w-md flex flex-col mb-4">
                  <label htmlFor="education">Lösenord</label>
                  <input
                    {...field}
                    value={value}
                    name={name}
                    onChange={onChange}
                    onBlur={onBlur}
                    type="password"
                    placeholder="Ange ditt lösenord..."
                    className="input bg-muted h-[40px] input-bordered w-full mt-2 rounded-md pl-2"
                  />
                  <p className="text-xs text-red-500 mt-1">
                    {errors?.password?.message}
                  </p>
                </div>
              )}
            />

            <div className="w-full flex items-center justify-between max-w-md text-primary mt-8 hover:text-muted">
              <Link href="/login" className="link">
                Inte en medlem?
              </Link>
              <Button>Logga in</Button>
              {/* <button className="btn btn-secondary" type="submit">
                Sign Up
              </button> */}
            </div>
          </form>
        </div>
      </Layout>
    </>
  );
};

export default Login;

import { zodResolver } from "@hookform/resolvers/zod";
import { NextPage } from "next";
import Head from "next/head";
import Link from "next/link";
import { useRouter } from "next/router";
import { Controller, useForm } from "react-hook-form";
import { trpc } from "../common/trpc";
import {
  createEducationSchema,
  CreateEducationInput,
  UpdateEducationInput,
  updateEducationSchema,
} from "../common/validation/education";
import { useCallback } from "react";

const EducationPage: NextPage = () => {
  const router = useRouter();
  const { handleSubmit, control, reset } = useForm<CreateEducationInput>({
    defaultValues: {
      name: "",
    },
    resolver: zodResolver(createEducationSchema),
  });

  const { mutateAsync } = trpc.education.create.useMutation();

  const onSubmit = useCallback(
    async (data: CreateEducationInput) => {
      try {
        const result = await mutateAsync(data);
      } catch (err) {
        console.error(err);
      }
    },
    [mutateAsync, router, reset]
  );

  return (
    <div>
      <Head>
        <title>Education</title>
        <meta name="description" content="Generated by create next app" />
        <link rel="icon" href="/favicon.ico" />
      </Head>

      <main>
        <form
          className="flex items-center justify-center h-44 w-full"
          onSubmit={handleSubmit(onSubmit)}
        >
          <div className="card w-96 bg-base-100 shadow-xl">
            <div className="card-body">
              <h2 className="card-title">Create an education</h2>
              <Controller
                name="name"
                control={control}
                render={({ field }) => (
                  <input
                    type="text"
                    placeholder="Type an education..."
                    className="input input-bordered w-full max-w-xs my-2"
                    {...field}
                  />
                )}
              />

              <div className="card-actions items-center justify-between">
                <Link href="/" className="link">
                  Go to login
                </Link>

                <button className="btn btn-secondary" type="submit">
                  Create
                </button>
              </div>
            </div>
          </div>
        </form>
        <form
          className="flex items-center justify-center h-44 w-full"
          onSubmit={handleSubmit(onSubmit)}
        >
          <div className="card w-96 bg-base-100 shadow-xl">
            <div className="card-body">
              <h2 className="card-title">Update an education</h2>
              <Controller
                name="name"
                control={control}
                render={({ field }) => (
                  <input
                    type="text"
                    placeholder="Type the education to change..."
                    className="input input-bordered w-full max-w-xs my-2"
                    {...field}
                  />
                )}
              />
              <Controller
                name="name"
                control={control}
                render={({ field }) => (
                  <input
                    type="text"
                    placeholder="Type the new education..."
                    className="input input-bordered w-full max-w-xs my-2"
                    {...field}
                  />
                )}
              />

              <div className="card-actions items-center justify-between">
                <Link href="/" className="link">
                  Go to login
                </Link>

                <button className="btn btn-secondary" type="submit">
                  Update
                </button>
              </div>
            </div>
          </div>
        </form>
      </main>
    </div>
  );
};

export default EducationPage;

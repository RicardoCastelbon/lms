import type { NextPage } from "next";
import Head from "next/head";
import Link from "next/link";
import { ChangeEvent, useCallback } from "react";
import { useRouter } from "next/router";
import { useForm, Controller } from "react-hook-form";
import { zodResolver } from "@hookform/resolvers/zod";
import Layout from "../components/ui/Layout";
import { Button } from "../components/ui/button";
import Select, { SingleValue } from "react-select";

import {
  signUpSchema,
  ISignUp,
  ILogin,
  loginSchema,
} from "../common/validation/auth";
import { trpc } from "../common/trpc";
import { log } from "console";

const educations = [
  { label: "Education 1", value: 1 },
  { label: "Education 2", value: 2 },
  { label: "Education 3", value: 3 },
  { label: "Education 4", value: 4 },
];

const SignUp: NextPage = () => {
  const router = useRouter();
  const { handleSubmit, control, register, setValue, reset } = useForm<ISignUp>(
    {
      defaultValues: {
        email: "",
        password: "",
        education: 1,
        firstName: "",
        lastName: "",
      },
      resolver: zodResolver(signUpSchema),
    }
  );

  const { mutateAsync } = trpc.users.signup.useMutation();

  const onSubmit = useCallback(
    async (data: ISignUp) => {
      console.log("hej");
      try {
        console.log(data);

        const result = await mutateAsync(data);
        if (result.status === 201) {
          reset();
          router.push("/login");
        }
      } catch (err) {
        console.error(err);
      }
    },
    [mutateAsync, router, reset]
  );

  const handleSelectChange = (e: ChangeEvent<HTMLSelectElement>) => {
    const value = Number(e.target.value);
    console.log(value);

    setValue("education", value);
  };

  return (
    <div>
      <Head>
        <title>Next App - Register</title>
        <meta name="description" content="Generated by create next app" />
        <link rel="icon" href="/favicon.ico" />
      </Head>
      <Layout>
        <div className="flex flex-1 items-center justify-center relative w-full h-full p-4">
          <form
            className="flex flex-col items-center gap-4 h-full w-full md:w-4/6 bg-white px-4 py-10 rounded-lg"
            onSubmit={handleSubmit(onSubmit)}
          >
            <h2 className="text-xl mb-8">Skapa ett konto</h2>
            <Controller
              name="education"
              control={control}
              rules={{ required: true }}
              render={({ field }) => (
                <div className="w-full max-w-md flex flex-col mb-4">
                  <label htmlFor="education">Choose education</label>
                  <select
                    className="input h-[40px] bg-muted input-bordered w-full mt-2 rounded-md"
                    name="education"
                    id="education"
                    onChange={(e) => handleSelectChange(e)}
                  >
                    <option value="default" disabled>
                      Choose education
                    </option>
                    <option value="1">Education 1</option>
                    <option value="2">Education 2</option>
                    <option value="3">Education 3</option>
                  </select>
                </div>
              )}
            />
            <Controller
              name="email"
              control={control}
              render={({ field }) => (
                <div className="w-full max-w-md flex flex-col mb-4">
                  <label htmlFor="email">Email</label>
                  <input
                    id="email"
                    type="email"
                    placeholder="Type your email..."
                    className="input bg-muted h-[40px] input-bordered w-full mt-2 rounded-md pl-2"
                    {...field}
                  />
                </div>
              )}
            />

            <Controller
              name="password"
              control={control}
              render={({ field }) => (
                <div className="w-full max-w-md flex flex-col mb-4">
                  <label htmlFor="password">Enter your password</label>
                  <input
                    id="password"
                    type="password"
                    placeholder="Type your password..."
                    className="input bg-muted h-[40px] input-bordered w-full mt-2 rounded-md pl-2"
                    {...field}
                  />
                </div>
              )}
            />
            <Controller
              name="firstName"
              control={control}
              render={({ field }) => (
                <div className="w-full max-w-md flex flex-col mb-4">
                  <label htmlFor="firstName">First name</label>
                  <input
                    id="firstName"
                    type="text"
                    placeholder="Your first name"
                    className="input bg-muted h-[40px] input-bordered w-full mt-2 rounded-md pl-2"
                    {...field}
                  />
                </div>
              )}
            />
            <Controller
              name="lastName"
              control={control}
              render={({ field }) => (
                <div className="w-full max-w-md flex flex-col">
                  <label htmlFor="lastName">Last name</label>
                  <input
                    id="lastName"
                    type="text"
                    placeholder="Type your email..."
                    className="input bg-muted h-[40px] input-bordered w-full rounded-md  mt-2 pl-2"
                    {...field}
                  />
                </div>
              )}
            />

            <div className="w-full flex items-center justify-between max-w-md text-primary mt-8 hover:text-muted">
              <Link href="/login" className="link">
                Go to login
              </Link>
              <Button>Become a member</Button>
            </div>
          </form>
        </div>
      </Layout>
    </div>
  );
};

export default SignUp;

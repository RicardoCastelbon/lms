import type {
  GetServerSideProps,
  GetServerSidePropsContext,
  NextPage,
} from "next";
import Head from "next/head";
import Link from "next/link";
import { ChangeEvent, useCallback } from "react";
import { useRouter } from "next/router";
import { useForm, Controller } from "react-hook-form";
import { zodResolver } from "@hookform/resolvers/zod";
import Layout from "../components/ui/Layout";
import { Button } from "../components/ui/button";
import Select, { SingleValue } from "react-select";

import { signUpSchema, ISignUp } from "../common/validation/auth";
import { trpc } from "../common/trpc";
import { getServerSession } from "next-auth";
import { nextAuthOptions } from "../common/auth";
import { createServerSideHelpers } from "@trpc/react-query/server";
import { serverRouter } from "../server/routers";
import { createContext } from "../server/context";
import { Education } from "@prisma/client";

const educations = [
  { label: "React", value: 1 },
  { label: "Angular", value: 2 },
  // { label: "Angular 2", value: "317774eb-7d44-4d01-a93a-22b3f30f17df" },
  // { label: "FWD22", value: "ea70de22-e81d-4c6c-a6e3-d1a18fe43aea" },
];
type Props = {
  educations: Education[];
};

const SignUp: NextPage<Props> = ({ educations }: Props) => {
  const router = useRouter();
  const { handleSubmit, control, register, setValue, reset } = useForm<ISignUp>(
    {
      defaultValues: {
        email: "",
        password: "",
        education: 0,
        firstName: "",
        lastName: "",
      },
      resolver: zodResolver(signUpSchema),
    }
  );
  // console.log("edu", educations);

  const { mutateAsync } = trpc.users.signup.useMutation();

  const onSubmit = useCallback(
    async (data: ISignUp) => {
      try {
        //data.userRole = "student";
        // console.log(data);
        const result = await mutateAsync(data);
        if (result.status) {
          reset();
          router.push("/login");
        } else {
          console.log(result.message);
        }
      } catch (err) {
        console.error(err);
      }
    },
    [mutateAsync, router, reset]
  );

  const handleSelectChange = (e: ChangeEvent<HTMLSelectElement>) => {
    const value = Number(e.target.value);
    console.log(value);

    setValue("education", value);
  };

  return (
    <div>
      <Head>
        <title>Next App - Register</title>
        <meta name="description" content="Generated by create next app" />
        <link rel="icon" href="/favicon.ico" />
      </Head>
      <Layout>
        <div className="flex flex-1 items-center justify-center relative w-full h-full p-4">
          <form
            className="flex flex-col items-center gap-4 h-full w-full md:w-4/6 bg-white px-4 py-10 rounded-lg"
            onSubmit={handleSubmit(onSubmit)}
          >
            <h2 className="text-xl mb-8">Skapa ett konto</h2>
            <Controller
              name="education"
              control={control}
              rules={{ required: true }}
              render={({ field }) => (
                <div className="w-full max-w-md flex flex-col mb-4">
                  <label htmlFor="education">Välj utbildning</label>
                  <select
                    className="input h-[40px] bg-muted input-bordered w-full mt-2 rounded-md"
                    // name="education"
                    id="education"
                    {...register("education", { required: true })}
                    onChange={(e) => handleSelectChange(e)}
                  >
                    {/* <option value="default">Välj utbildning</option> */}
                    {educations?.map((edu) => (
                      <option key={edu.id} value={edu.id}>
                        {edu.name}
                      </option>
                    ))}
                  </select>
                </div>
              )}
            />
            <Controller
              name="email"
              control={control}
              render={({ field }) => (
                <div className="w-full max-w-md flex flex-col mb-4">
                  <label htmlFor="email">Ange din email</label>
                  <input
                    id="email"
                    type="email"
                    placeholder="Type your email..."
                    className="input bg-muted h-[40px] input-bordered w-full mt-2 rounded-md pl-2"
                    {...field}
                    {...register("email", { required: true })}
                  />
                </div>
              )}
            />

            <Controller
              name="password"
              control={control}
              render={({ field }) => (
                <div className="w-full max-w-md flex flex-col mb-4">
                  <label htmlFor="password">Ange ett lösenord</label>
                  <input
                    id="password"
                    type="password"
                    placeholder="Type your password..."
                    className="input bg-muted h-[40px] input-bordered w-full mt-2 rounded-md pl-2"
                    {...field}
                    {...register("password", { required: true })}
                  />
                </div>
              )}
            />
            <Controller
              name="firstName"
              control={control}
              render={({ field }) => (
                <div className="w-full max-w-md flex flex-col mb-4">
                  <label htmlFor="firstName">Namn</label>
                  <input
                    id="firstName"
                    type="text"
                    placeholder="Your first name"
                    className="input bg-muted h-[40px] input-bordered w-full mt-2 rounded-md pl-2"
                    {...field}
                    {...register("firstName", { required: true })}
                  />
                </div>
              )}
            />
            <Controller
              name="lastName"
              control={control}
              render={({ field }) => (
                <div className="w-full max-w-md flex flex-col">
                  <label htmlFor="lastName">Efternamn</label>
                  <input
                    id="lastName"
                    type="text"
                    placeholder="Type your email..."
                    className="input bg-muted h-[40px] input-bordered w-full rounded-md  mt-2 pl-2"
                    {...field}
                    {...register("lastName", { required: true })}
                  />
                </div>
              )}
            />

            <div className="w-full flex items-center justify-between gap-4 max-w-md  mt-8">
              <span>
                Har du redan ett konto?
                <Link
                  href="/login"
                  className="link ml-2 text-primary hover:text-secondary"
                >
                  Logga in
                </Link>
              </span>
              <Button className="hover:bg-background hover:text-foreground">
                Skapa konto
              </Button>
            </div>
          </form>
        </div>
      </Layout>
    </div>
  );
};
export const getServerSideProps: GetServerSideProps = async (context: any) => {
  const currentSession = await getServerSession(
    context.req,
    context.res,
    nextAuthOptions
  );
  // const educationId = String(currentSession?.user.educationId);

  //Set up a trpc helper, needed for serverSide fetching
  const helpers = createServerSideHelpers({
    router: serverRouter,
    ctx: await createContext(context),
  });

  //The actual fetching
  const res = await helpers.education.getAll.fetch();

  //Needed to serialize Date objects for createdAt + updatedAt otherwise error is thrown
  const educations = JSON.parse(JSON.stringify(res));
  console.log(educations.education);

  return {
    props: {
      session: currentSession,
      educations: educations.education,
    },
  };
};

export default SignUp;
